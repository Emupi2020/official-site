export const t = value => korean ? translations.get(value) ?? value : value;
export const listenerError = error => {
  if (!korean) return error.message;
  if (translations.has(error.message)) return t(error.message);
  const fieldLength = /^(Pocochaの名前|アーティスト名|曲名)は1〜(\d+)文字で入力してください。$/.exec(error.message);
  if (fieldLength) return `${t(fieldLength[1])}: 1~${fieldLength[2]}자로 입력해 주세요.`;
  if (error.status === 429) return '요청이 너무 많아요. 잠시 후 다시 시도해 주세요.';
  if (error.status === 401) return '다시 로그인해 주세요.';
  return '처리하지 못했어요. 입력 내용을 확인하거나 잠시 후 다시 시도해 주세요.';
};

export function localizeListenerPage() {
  if (korean) {
    document.documentElement.lang = 'ko';
    document.title = t(document.title);
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
      const node = walker.currentNode;
      if (node.parentElement.closest('script, style, option, [data-language-switch]')) continue;
      const label = node.data.trim();
      if (translations.has(label)) node.data = node.data.replace(label, t(label));
    }
    for (const element of document.querySelectorAll('[aria-label], [placeholder]')) {
      for (const attr of ['aria-label', 'placeholder']) {
        if (element.hasAttribute(attr)) element.setAttribute(attr, t(element.getAttribute(attr)));
      }
    }
    for (const option of document.querySelectorAll('option')) {
      if (/[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}]/u.test(option.textContent)) option.lang = 'ja';
    }
  }
  for (const control of document.querySelectorAll('[data-language-switch]')) {
    control.lang = korean ? 'ja' : 'ko';
    control.textContent = korean ? '🇯🇵 日本語' : '🇰🇷 한국어';
    control.onclick = () => {
      if (!safeSet(languageKey, korean ? 'ja' : 'ko')) return;
      history.replaceState({...history.state, restoreLanguageView:true}, '');
      location.reload();
    };
  }
}
